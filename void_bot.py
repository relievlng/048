def _gen_key(prefix: str = "VD") -> str:
    charset = string.ascii_uppercase + string.digits
    parts = ["".join(secrets.choice(charset) for _ in range(5)) for _ in range(4)]
    return f"{prefix}-" + "-".join(parts)

