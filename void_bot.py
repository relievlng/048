# ─── TICKET SYSTEM ────────────────────────────────────────────────────────────

_ticket_lock = asyncio.Lock()

async def _next_ticket_number(guild_id: int) -> int:
    row = DB.execute(
        "SELECT COUNT(*) AS cnt FROM tickets WHERE guild_id=? AND bot_source='void'", (str(guild_id),)
    ).fetchone()
    return (row["cnt"] or 0) + 1


async def _open_ticket(interaction: discord.Interaction, category_id: str) -> None:
    async with _ticket_lock:
        cat = TICKET_CATEGORIES.get(category_id)
        if not cat:
            await interaction.response.send_message("Unknown category.", ephemeral=True)
            return

        # Check for existing open ticket in this category
        existing = DB.execute(
            "SELECT channel_id FROM tickets WHERE discord_id=? AND guild_id=? AND category=? AND status='open' AND bot_source='void'",
            (str(interaction.user.id), str(interaction.guild.id), category_id)
        ).fetchone()
        if existing:
            ch = interaction.guild.get_channel(int(existing["channel_id"]))
            if ch:
                await interaction.response.send_message(
                    f"You already have an open {cat['label']} ticket: {ch.mention}", ephemeral=True
                )
                return

        await interaction.response.defer(ephemeral=True)

        guild = interaction.guild
        num   = await _next_ticket_number(guild.id)

        # Resolve ticket category channel - per-category first, then global fallback
        ticket_cat = None
        per_cat_id = CONFIG.get(cat.get("config_key", ""), 0)
        if per_cat_id:
            ticket_cat = guild.get_channel(per_cat_id)
            if not ticket_cat:
                try:
                    ticket_cat = await guild.fetch_channel(per_cat_id)
                except Exception:
                    ticket_cat = None
        if not ticket_cat:
            fallback_id = CONFIG.get("ticket_category_id", 0)
            if fallback_id:
                ticket_cat = guild.get_channel(fallback_id)
                if not ticket_cat:
                    try:
                        ticket_cat = await guild.fetch_channel(fallback_id)
                    except Exception:
                        ticket_cat = None
        if not ticket_cat:
            # Auto-find or create a category matching this ticket type
            cat_name = cat.get("cat_name", f"{cat['label']} Tickets")
            for c in guild.categories:
                if c.name.upper() == cat_name.upper():
                    ticket_cat = c
                    break
        if not ticket_cat:
            cat_name = cat.get("cat_name", "Tickets")
            ticket_cat = await guild.create_category(cat_name)

        # Permissions
        overwrites = {
            guild.default_role: discord.PermissionOverwrite(read_messages=False),
            interaction.user:   discord.PermissionOverwrite(
                read_messages=True, send_messages=True, attach_files=True, embed_links=True
            ),
            guild.me: discord.PermissionOverwrite(
                read_messages=True, send_messages=True, manage_channels=True, manage_messages=True
            ),
        }
        staff_role_id  = CONFIG.get("staff_role_id", 0)
        admin_role_id  = CONFIG.get("admin_role_id", 0)
        for role_id in (staff_role_id, admin_role_id):
            if role_id:
                role = guild.get_role(role_id)
                if role:
                    overwrites[role] = discord.PermissionOverwrite(
                        read_messages=True, send_messages=True,
                        manage_messages=True, manage_channels=True
                    )

        channel = await ticket_cat.create_text_channel(
            name=f"{category_id}-{num:04d}",
            overwrites=overwrites,
            topic=f"Ticket #{num:04d} | {cat['label']} | {interaction.user.display_name}",
        )

        DB.execute(
            """INSERT INTO tickets
               (channel_id, guild_id, bot_source, discord_id, category, type, opened_at, ticket_num)
               VALUES (?,?,?,?,?,?,?,?)""",
            (str(channel.id), str(guild.id), 'void',
             str(interaction.user.id), category_id, category_id, now_iso(), f"{num:04d}")
        )
        DB.commit()

        # Build opening panel
        em_ticket = _emoji_in_text("ticket")
        em_dot    = _emoji_in_text("dot")
        pfx    = f"{em_ticket} " if em_ticket else "\U0001f3ab "
        bullet = f"{em_dot} "   if em_dot   else "- "

        body: list = []
        body.append({"type": 10, "content": (
            f"## {pfx}Ticket #{num:04d} - {cat['label']}\n"
            f"-# Opened by {interaction.user.mention}"
        )})
        body.append({"type": 14})
        body.append({"type": 10, "content": (
            f"{bullet}Describe your issue or request below.\n"
            f"{bullet}Staff will be with you shortly.\n"
            f"{bullet}Use the **Close** button when resolved."
        )})

        payload = _v2_container(body, accent=BRAND_COLOR)
        await _post_channel_v2(channel, payload)

        # Ping the user and staff role, then post control buttons
        ping_parts = [interaction.user.mention]
        if staff_role_id:
            ping_parts.append(f"<@&{staff_role_id}>")
        elif admin_role_id:
            ping_parts.append(f"<@&{admin_role_id}>")
        await channel.send(content=" ".join(ping_parts), view=TicketControlView())

        await interaction.followup.send(
            f"Your ticket has been opened: {channel.mention}", ephemeral=True
        )
        log.info("Opened ticket %04d (%s) for %s", num, category_id, interaction.user.id)


