def _webhook_post_sync(url: str, payload: dict) -> None:
    """Fire a webhook synchronously (stdlib only - safe from HTTP handler thread)."""
    if not url:
        return
    try:
        import urllib.request as _ur
        data = json.dumps(payload).encode()
        req  = _ur.Request(url, data=data, headers={"Content-Type": "application/json"}, method="POST")
        with _ur.urlopen(req, timeout=4):
            pass
    except Exception as exc:
        log.warning("[webhook] post failed: %s", exc)


def _build_event_embed(discord_id, hwid, ip, event_type, product, system, geo, note) -> dict:
    """Build a Discord embed dict for a cheat event."""
    cfg = _EVENT_WEBHOOK_MAP.get(event_type, ("webhook_loader_events", 0x99AAB5, event_type.upper()))
    label = cfg[2]
    color = cfg[1]

    sys = system or {}
    extra = sys.get("extra") or {}
    note_str = note or extra.get("note", "")

    # Location line
    loc_parts = []
    if geo.get("country"):
        loc_parts.append(geo["country"])
    if geo.get("city"):
        loc_parts.append(geo["city"])
    loc = ", ".join(loc_parts) if loc_parts else "Unknown"
    if geo.get("vpn"):
        loc += " [VPN/Proxy]"

    fields = []
    if discord_id:
        fields.append({"name": "User", "value": f"<@{discord_id}> (`{discord_id}`)", "inline": True})
    if product:
        fields.append({"name": "Product", "value": product, "inline": True})
    if hwid:
        fields.append({"name": "HWID", "value": f"`{hwid[:20]}...`", "inline": True})
    if ip:
        fields.append({"name": "IP", "value": f"`{ip}`", "inline": True})
    fields.append({"name": "Location", "value": loc, "inline": True})
    if geo.get("isp"):
        fields.append({"name": "ISP", "value": geo["isp"][:50], "inline": True})

    sys_parts = []
    if sys.get("os"):
        sys_parts.append(sys["os"])
    if sys.get("cpu"):
        sys_parts.append(sys["cpu"][:40])
    if sys.get("ram"):
        sys_parts.append(sys["ram"])
    if sys.get("screen"):
        sys_parts.append(sys["screen"])
    if sys_parts:
        fields.append({"name": "System", "value": "\n".join(sys_parts), "inline": False})
    if note_str:
        fields.append({"name": "Note", "value": note_str[:500], "inline": False})

    return {
        "embeds": [{
            "title":     f"[{label}]",
            "color":     color,
            "fields":    fields,
            "timestamp": _now_iso(),
        }]
    }


def _log_event(discord_id: str | None, hwid: str | None, ip: str | None,
               event_type: str, product: str | None,
               system: dict | None, conn: sqlite3.Connection):
    """
    Write a row to the events table, runs geolocation, and posts to the
    appropriate staff Discord webhook.
    `system` dict keys (all optional): os, build, cpu, ram, screen, locale, hostname, extra
    """
    geo = _geolocate(ip) if ip else {}
    sys = system or {}
    extra = sys.get("extra") or {}
    note  = extra.get("note", "") if isinstance(extra, dict) else ""

    conn.execute(
        """INSERT INTO events
           (discord_id, hwid, ip, timestamp, event_type, product,
            geo_country, geo_city, geo_isp, geo_vpn,
            sys_os, sys_build, sys_cpu, sys_ram, sys_screen, sys_locale, sys_hostname,
            metadata)
           VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
        (
            discord_id, hwid, ip, _now_iso(), event_type, product,
            geo.get("country"), geo.get("city"), geo.get("isp"), geo.get("vpn", 0),
            sys.get("os"), sys.get("build"), sys.get("cpu"),
            sys.get("ram"), sys.get("screen"), sys.get("locale"), sys.get("hostname"),
            json.dumps(sys.get("extra")) if sys.get("extra") else None,
        )
    )

    # Post to staff Discord webhook (non-blocking, synchronous urllib)
    wh_cfg_key = _EVENT_WEBHOOK_MAP.get(event_type, ("webhook_loader_events",))[0]
    wh_url     = CONFIG.get(wh_cfg_key, "")
    if wh_url:
        embed_payload = _build_event_embed(
            discord_id, hwid, ip, event_type, product, sys, geo, note
        )
        _webhook_post_sync(wh_url, embed_payload)

