        "ALTER TABLE tickets ADD COLUMN guild_id TEXT NOT NULL DEFAULT ''",
        "ALTER TABLE tickets ADD COLUMN bot_source TEXT NOT NULL DEFAULT 'void'",
        "ALTER TABLE tickets ADD COLUMN category TEXT NOT NULL DEFAULT ''",
