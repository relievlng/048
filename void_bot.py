def _v2_section(text: str, btn_label: str, btn_custom_id: str,
                btn_emoji_name: str = "", btn_style: int = 2) -> dict:
    btn: dict = {"type": 2, "style": btn_style, "label": btn_label, "custom_id": btn_custom_id}
